class ModelBuilderController:
    """Pure controller shared by the native UI and automated tests."""

    def __init__(self, catalog: Optional[Mapping[str, Any]] = None):
        """Bind the controller to a feature catalog (default: the built-in one)."""

        self.catalog = dict(catalog or build_feature_catalog())

    def variants_for_class(self, target_class: str):
        """Return the model variants available for one SIA 4010 target class."""

        return tuple(self.catalog["classes"][target_class])

    def cases_for_variant(self, variant: str):
        """Return the official test cases covered by one model variant."""

        return tuple(self.catalog["cases"][variant])

    @staticmethod
    def ensure_test1_weather(
        project_path: Path,
        repository_root: Path,
    ) -> Path:
        """Return project-local verified DRYCOLD weather for Test 1.

        An operator-supplied weather file is preserved when it is the only
        supported weather file in the saved project. Otherwise the bundled,
        checksum-verified BESTEST EPW and its adjacent derivation report are
        copied without ever overwriting different project content.
        """

        project = Path(project_path)
        repository = Path(repository_root)
        source_directory = (
            repository / "references" / "standards" / "bestest"
        )
        filenames = (
            "DRYCOLD_IESVE.epw",
            "DRYCOLD_IESVE_EPW_DERIVATION.json",
        )

        def checksum(path: Path) -> str:
            """Return SHA-256 for collision-safe controlled input copying."""

            return hashlib.sha256(path.read_bytes()).hexdigest()

        existing = discover_weather_file(project)
        if existing is not None:
            source_weather = source_directory / filenames[0]
            project_audit = project / filenames[1]
            source_tmy = source_directory / "DRYCOLD.TMY"
            if (
                existing.name != filenames[0]
                or not source_weather.is_file()
                or checksum(existing) == checksum(source_weather)
            ):
                return existing

            # Migrate only a weather artifact whose adjacent audit proves it
            # was generated by this controlled TMY1 transport.  A different
            # operator-supplied EPW is never overwritten.
            managed = False
            if project_audit.is_file() and source_tmy.is_file():
                try:
                    audit = json.loads(
                        project_audit.read_text(encoding="utf-8")
                    )
                    accepted_source_checksums = {
                        checksum(source_tmy).upper()
                    }
                    source_verification = (
                        source_directory
                        / "DRYCOLD_TMY_ISO_SOURCE_VERIFICATION.json"
                    )
                    if source_verification.is_file():
                        verification = json.loads(
                            source_verification.read_text(encoding="utf-8")
                        )
                        accepted_source_checksums.add(
                            str(
                                verification["weather"]["sha256"]
                            ).upper()
                        )
                    managed = (
                        audit.get("status") == "PASS"
                        and audit["weather"].get("format") == "EPW"
                        and str(audit["weather"]["sha256"]).upper()
                        == checksum(existing).upper()
                        and audit["source_tmy1"].get("format")
                        == "NOAA_TMY1_FIXED_WIDTH"
                        and str(
                            audit["source_tmy1"]["sha256"]
                        ).upper()
                        in accepted_source_checksums
                    )
                except (KeyError, OSError, TypeError, ValueError):
                    managed = False
            if not managed:
                return existing

            backup_weather = project / (
                "DRYCOLD_IESVE.pre_iso_sky_boundary.epw.bak"
            )
            backup_audit = project / (
                "DRYCOLD_IESVE_EPW_DERIVATION.pre_iso_sky_boundary.json"
            )
            for current, backup in (
                (existing, backup_weather),
                (project_audit, backup_audit),
            ):
                if backup.exists():
                    if (
                        not backup.is_file()
                        or checksum(backup) != checksum(current)
                    ):
                        raise FileExistsError(
                            "Controlled weather backup collision: {}".format(
                                backup
                            )
                        )
                else:
                    shutil.copy2(str(current), str(backup))
            shutil.copy2(str(source_weather), str(existing))
            shutil.copy2(
                str(source_directory / filenames[1]),
                str(project_audit),
            )
            return existing

        for filename in filenames:
            source = source_directory / filename
            destination = project / filename
            if not source.is_file():
                raise FileNotFoundError(
                    "Controlled Test 1 weather input is missing: {}".format(
                        source
                    )
                )
            if destination.exists():
                if (
                    not destination.is_file()
                    or checksum(source) != checksum(destination)
                ):
                    raise FileExistsError(
                        "A different Test 1 weather artifact was not "
                        "overwritten: {}".format(destination)
                    )
            else:
                shutil.copy2(str(source), str(destination))
        return project / filenames[0]

    @staticmethod
    def prepare_supported_mvp_bundle(
        project_path: Path,
        repository_root: Path,
        profile: str,
        variant: str,
        case_id: str,
    ) -> Optional[object]:
        """Generate a specialized lightweight Test 1 project-local bundle."""

        if str(profile).upper() != "SIA4010_OFFICIAL" or variant != "test_1":
            return None
        if case_id not in {
            "600",
            "640",
            "600FF",
            "900",
            "940",
            "900FF",
        }:
            return None
        weather_file = ModelBuilderController.ensure_test1_weather(
            project_path, repository_root
        )
        if case_id == "600":
            return build_case600_mvp_bundle(
                project_path, repository_root, weather_file=weather_file
            )
        if case_id in {"640", "600FF", "900", "940", "900FF"}:
            return build_test1_runtime_probe_bundle(
                project_path,
                repository_root,
                case_id,
                weather_file=weather_file,
            )
        return None

    @staticmethod
    def prepare_case_bundle(
        project_path: Path,
        repository_root: Path,
        profile: str,
        target_class: str,
        variant: str,
        case_id: str,
    ) -> Optional[object]:
        """Generate source-traced project artifacts for any official case."""

        if str(profile).upper() != "SIA4010_OFFICIAL":
            return None
        specialized = ModelBuilderController.prepare_supported_mvp_bundle(
            project_path, repository_root, profile, variant, case_id
        )
        if specialized is not None:
            return specialized
        if variant == "test_2A" and case_id == "2A":
            delegated = external_input_readiness(
                project_path,
                variant,
                case_id,
            )
            if delegated.ready_for_binding:
                return build_test2a_source_bound_bundle(
                    project_path,
                    repository_root,
                )
        if variant in TEST3_VARIANTS and case_id == variant[5:]:
            delegated = external_input_readiness(
                project_path,
                variant,
                case_id,
            )
            if delegated.ready_for_binding:
                return build_test3_source_bound_bundle(
                    project_path,
                    repository_root,
                    target_class,
                    variant,
                    case_id,
                )
        # Every other exact case still produces a useful, checksum-traced
        # preparation artifact. It remains fail-closed until both its official
        # input binding and guarded VE generator are implemented.
        return prepare_case(
            project_path,
            repository_root,
            target_class,
            variant,
            case_id,
        )

