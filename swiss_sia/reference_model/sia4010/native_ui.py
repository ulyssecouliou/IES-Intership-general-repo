    @staticmethod
    def _qualification_report_is_valid(
        reports: Any,
        *,
        required_true_field: Optional[str] = None,
        required_false_field: Optional[str] = None,
    ) -> bool:
        """Validate one immutable qualification report and its SHA sidecar."""

        report_paths = tuple(Path(path) for path in reports)
        if len(report_paths) != 1:
            return False
        report_path = report_paths[0]
        checksum_path = report_path.with_suffix(
            report_path.suffix + ".sha256"
        )
        if not report_path.is_file() or not checksum_path.is_file():
            return False
        try:
            expected_sha = checksum_path.read_text(
                encoding="utf-8"
            ).split()[0]
            actual_sha = hashlib.sha256(report_path.read_bytes()).hexdigest()
            payload = json.loads(report_path.read_text(encoding="utf-8"))
        except (IndexError, OSError, ValueError, TypeError):
            return False
        if expected_sha != actual_sha or payload.get("status") != "PASS":
            return False
        if (
            required_true_field is not None
            and payload.get(required_true_field) is not True
        ):
            return False
        if (
            required_false_field is not None
            and payload.get(required_false_field) is not False
        ):
            return False
        return True

