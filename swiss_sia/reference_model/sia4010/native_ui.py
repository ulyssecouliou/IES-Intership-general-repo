    def _run(self, execution_mode: str) -> None:
        """Write and validate the scenario, then report the outcome in the UI."""

        bundle = None
        try:
            bundle = self.controller.prepare_case_bundle(
                self.project_path,
                self.repository_root,
                self.profile_var.get(),
                self.class_var.get(),
                self.variant_var.get(),
                self.case_var.get(),
            )
            if bundle is not None:
                project_files = (
                    getattr(bundle, "case_manifest_path", None),
                    getattr(bundle, "config_path", None),
                    getattr(bundle, "asset_manifest_path", None),
                )
                if all(project_files):
                    self.case_manifest_var.set(str(project_files[0]))
                    self.ve_config_var.set(str(project_files[1]))
                    self.ve_assets_var.set(str(project_files[2]))
                self._append_log(
                    "{} - {} : {}".format(
                        bundle.status,
                        self.t("log_mvp_bundle"),
                        bundle.audit_path,
                    )
                )
            payload = self._payload(execution_mode)
            scenario = self.controller.write_and_validate(
                self.project_path, payload
            )
        except Exception as exc:
            self._set_status("error", self.t("status_invalid_title"), str(exc))
            self._append_log("FAIL - {}".format(exc))
            messagebox.showerror(
                self.t("dlg_invalid_scenario"), str(exc), parent=self.master
            )
            return

        self._set_status(
            "warning",
            self.t("status_processing_title"),
            self.t("status_processing_detail"),
        )
        self._append_log(
            "{} - {}/{} - {}".format(
                execution_mode,
                scenario.variant,
                scenario.case_id,
                self.project_path / SCENARIO_FILENAME,
            )
        )
        self.master.update_idletasks()
        try:
            result = self.executor()
        except Exception as exc:
            self._set_status("error", self.t("status_failed_title"), str(exc))
            self._append_log("FAIL - {}".format(exc))
            messagebox.showerror(
                "Swiss VE Model Builder", str(exc), parent=self.master
            )
            return

        payload_result = (
            result.to_dict() if hasattr(result, "to_dict") else {}
        )
        status = str(
            payload_result.get("status")
            or getattr(getattr(result, "status", None), "value", "")
            or getattr(result, "status", "PASS")
        )
        blockers = payload_result.get("blockers", [])
        preparation_status = str(getattr(bundle, "status", "") or "")
        preparation_blockers = list(getattr(bundle, "blockers", ()) or ())
        if (
            execution_mode == "PREPARE_ONLY"
            and (
                "BLOCKED" in preparation_status
                or "WITH_BLOCKERS" in preparation_status
            )
        ):
            # The launcher may correctly return READY_FOR_PREPARATION because
            # no mutation was attempted. Preserve the stricter source/generator
            # preparation status in the operator-facing banner.
            status = preparation_status
            blockers = preparation_blockers or blockers
        if "BLOCKED" in status or blockers:
            detail = "\n".join(str(item) for item in blockers[:4])
            self._set_status(
                "warning",
                status or self.t("status_blocked_title"),
                detail or self.t("status_blocked_detail"),
            )
        elif "FAIL" in status:
            self._set_status(
                "error", status, self.t("status_audit_detail")
            )
        else:
            self._set_status(
                "ready",
                status or self.t("status_done_title"),
                self.t("status_done_detail"),
            )
        self._append_log(
            "{} - {}".format(status or "PASS", self.t("log_operation_done"))
        )
        self._sync_case()

    def prepare(self) -> None:
        """Prepare geometry and preflight without mutating VE."""

        self._run("PREPARE_ONLY")

