    @staticmethod
    def prepare_validation_class(
        project_path: Path,
        repository_root: Path,
        target_class: str,
    ) -> ClassPreparationReceipt:
        """Prepare every exact case required by one selected SIA 4010 class."""

        return prepare_class(project_path, repository_root, target_class)

    @staticmethod
    def prepare_every_validation_class(
        project_path: Path,
        repository_root: Path,
    ) -> AllClassesPreparationReceipt:
        """Prepare the full eight-class execution index in one verified pass."""

        receipt = prepare_all_classes(project_path, repository_root)
        autonomy = Path(repository_root) / "sia4010_evidence" / "autonomy"
        registry = autonomy / "sia4010_case_evidence.json"
        synchronize_preparation(registry, receipt)
        ModelBuilderController.rebuild_evidence_navigator(repository_root)
        return receipt

    @staticmethod
    def rebuild_evidence_navigator(repository_root: Path) -> Dict[str, Any]:
        """Rebuild the eight-class navigator from the checksummed ledger."""

        root = Path(repository_root)
        autonomy = root / "sia4010_evidence" / "autonomy"
        registry = autonomy / "sia4010_case_evidence.json"
        if not registry.is_file():
            raise FileNotFoundError(
                "SIA 4010 evidence ledger does not exist: {}".format(registry)
            )
        return build_all_class_navigators(
            registry,
            root / "SIA_4010_geteilter_Link",
            autonomy / "navigator",
        )

    @staticmethod
    def ensure_external_input_manifest(
        project_path: Path,
        repository_root: Path,
    ):
        """Create the project-local delegated-input template once and validate it.

        An existing manifest is never overwritten.  This action only exposes
        the evidence contract to the operator; it does not authorize any input
        or enable any VE generator.
        """

        project = Path(project_path)
        repository = Path(repository_root)
        if not project.is_dir():
            raise FileNotFoundError(
                "Saved VE project directory does not exist: {}".format(project)
            )
        template = (
            repository / "config" / "sia4010_external_inputs.example.json"
        )
        if not template.is_file():
            raise FileNotFoundError(
                "External-input template does not exist: {}".format(template)
            )
        target = project / EXTERNAL_INPUT_FILENAME
        created = False
        if not target.exists():
            shutil.copyfile(str(template), str(target))
            created = True
        elif not target.is_file():
            raise FileExistsError(
                "External-input manifest path is not a file: {}".format(target)
            )
        # Reject malformed or misspelled contracts before opening them.
        Sia4010ExternalInputManifest.load(target)
        source_templates = repository / "config" / "external_input_examples"
        project_templates = project / "sia4010_external_input_templates"
        if not source_templates.is_dir():
            raise FileNotFoundError(
                "External-input binding templates do not exist: {}".format(
                    source_templates
                )
            )
        project_templates.mkdir(parents=True, exist_ok=True)
        for source in sorted(source_templates.glob("*.json")):
            destination = project_templates / source.name
            if not destination.exists():
                shutil.copyfile(str(source), str(destination))
            elif not destination.is_file():
                raise FileExistsError(
                    "External-input template path is not a file: {}".format(
                        destination
                    )
                )
        return target, created

    def build_payload(
        self,
        scenario_id: str,
        profile: str,
        target_class: str,
        variant: str,
        case_id: str,
        execution_mode: str,
        case_manifest_file: str,
        ve_config_file: str,
        ve_asset_manifest_file: str,
        custom_features: Optional[Mapping[str, bool]] = None,
    ) -> Dict[str, Any]:
        """Build a payload accepted by the strict ModelScenario loader."""

        normalized_profile = str(profile).upper()
        if normalized_profile == "SIA4010_OFFICIAL":
            features = official_features(variant, case_id)
        else:
            features = {
                feature_id: bool((custom_features or {}).get(feature_id, False))
                for feature_id in FEATURE_IDS
            }
            execution_mode = "PREPARE_ONLY"
        return {
            "schema_version": "1.0",
            "scenario_id": str(scenario_id).strip(),
            "profile": normalized_profile,
            "selection": {
                "target_class": target_class,
                "variant": variant,
                "case_id": case_id,
            },
            "features": features,
            "files": {
                "case_manifest_file": str(case_manifest_file).strip(),
                "ve_config_file": str(ve_config_file).strip(),
                "ve_asset_manifest_file": str(ve_asset_manifest_file).strip(),
            },
            "execution": {"mode": execution_mode},
        }

    @staticmethod
    def write_and_validate(
        project_path: Path, payload: Mapping[str, Any]
    ) -> ModelScenario:
        """Write the active-project scenario and validate the persisted file."""

        scenario_path = Path(project_path) / SCENARIO_FILENAME
        scenario_path.write_text(
            json.dumps(payload, indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8",
        )
        return ModelScenario.load(scenario_path)


